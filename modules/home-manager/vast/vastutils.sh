# vastutils — manage SSH access and GitHub deploy keys for vast.ai instances.
# Packaged by modules/home-manager/vast; see docs/vast.md.

VAST_CONF="${VASTUTILS_SSH_CONF:-$HOME/.ssh/config.d/vast.conf}"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/vastutils"
KEYS_DB="$STATE_DIR/deploy-keys.tsv" # lines: <owner/repo>\t<vast-ID>

# SSH options for scripted connections: never prompt, and don't try to bind the
# interactive LocalForwards (8080 may already be taken by an open session).
SSH_OPTS=(-o BatchMode=yes -o ClearAllForwardings=yes -o ConnectTimeout=15)

usage() {
  cat <<'EOF'
vastutils — SSH aliases and per-instance GitHub deploy keys for vast.ai

USAGE
  vastutils sync [--no-reap]
  vastutils bootstrap <vast-ID|vast> <owner/repo>...
  vastutils status
  vastutils help

COMMANDS
  sync        Regenerate ~/.ssh/config.d/vast.conf from your running instances,
              then reap: delete every deploy key that bootstrap created for an
              instance that is no longer running.
                vast-<ID>  one alias per running instance
                vast       the most recently started instance
              --no-reap    only regenerate the SSH config

  bootstrap   Give an instance push/pull access to one or more GitHub repos.
              For each repo, a fresh ed25519 key is generated ON the instance
              (the private key never leaves it), its public half is added as a
              write-enabled deploy key titled "vast-<ID>", and git on the
              instance is configured so these URLs use that key:
                https://github.com/<owner>/<repo>.git
                git@github.com:<owner>/<repo>.git
              Safe to re-run; already-registered keys are skipped.

  status      Show running instances and the deploy keys bootstrap has recorded.

TYPICAL FLOW
  vastai tfa login ...                     # when the 2FA session has expired
  vastutils sync                           # after creating/destroying instances
  vastutils bootstrap vast owner/repo      # once per new instance
  ssh vast                                 # port 8080 is forwarded

REQUIREMENTS
  vastai with a valid API key and 2FA session; `gh auth login` done once with
  admin rights on the target repos.

FILES
  ~/.ssh/config.d/vast.conf                 generated SSH aliases (overwritten)
  ~/.local/state/vastutils/deploy-keys.tsv  deploy keys to reap later

See docs/vast.md in ~/Code/tilde for the full design.
EOF
}

die() {
  echo "vastutils: $*" >&2
  exit 1
}

# Running instances as JSON lines: {id, host, port, start}. Fails loudly (and
# never returns an empty list) if the API call fails, so a 2FA error can't make
# sync think everything has been destroyed.
running_instances() {
  local raw
  if ! raw=$(vastai show instances --raw 2>&1); then
    die "vastai show instances failed (2FA session expired? run 'vastai tfa login'):
$raw"
  fi
  jq -e 'type == "array"' <<<"$raw" >/dev/null 2>&1 ||
    die "unexpected response from vastai: $raw"
  jq -c '
    .[] | select(.actual_status == "running" and .ssh_host != null)
    | {id, host: .ssh_host, port: .ssh_port, start: .start_date}
  ' <<<"$raw"
}

write_ssh_conf() {
  local instances=$1 tmp
  mkdir -p "$(dirname "$VAST_CONF")"
  tmp=$(mktemp "$VAST_CONF.XXXXXX")
  {
    echo "# Generated by 'vastutils sync' on $(date -Is). Do not edit."
    echo "# Shared options (user, key, forwards) live in the 'vast vast-* *.vast.ai'"
    echo "# block of the home-manager SSH config."
    jq -sr '
      sort_by(.start)
      | (.[] | "\nHost vast-\(.id)\n  HostName \(.host)\n  Port \(.port)"),
        (last // empty | "\n# newest instance (vast-\(.id))\nHost vast\n  HostName \(.host)\n  Port \(.port)")
    ' <<<"$instances"
  } >"$tmp"
  chmod 600 "$tmp"
  mv "$tmp" "$VAST_CONF"
  echo "wrote $VAST_CONF ($(jq -s length <<<"$instances") running instance(s))"
}

reap() {
  local instances=$1 repo title id key_ids kept
  [[ -s $KEYS_DB ]] || { echo "reap: no recorded deploy keys"; return 0; }
  kept=$(mktemp)
  while IFS=$'\t' read -r repo title; do
    [[ -n $repo ]] || continue
    id=${title#vast-}
    if jq -se --argjson id "$id" 'any(.[]; .id == $id)' <<<"$instances" >/dev/null; then
      printf '%s\t%s\n' "$repo" "$title" >>"$kept"
      continue
    fi
    if ! key_ids=$(gh repo deploy-key list --repo "$repo" --json id,title \
      --jq ".[] | select(.title == \"$title\") | .id"); then
      echo "reap: could not list keys for $repo; keeping record" >&2
      printf '%s\t%s\n' "$repo" "$title" >>"$kept"
      continue
    fi
    for kid in $key_ids; do
      gh repo deploy-key delete "$kid" --repo "$repo" &&
        echo "reap: deleted deploy key '$title' from $repo"
    done
    [[ -n $key_ids ]] || echo "reap: '$title' already gone from $repo"
  done <"$KEYS_DB"
  sort -u "$kept" >"$KEYS_DB"
  rm -f "$kept"
}

cmd_sync() {
  local do_reap=1 instances
  case "${1:-}" in
    "") ;;
    --no-reap) do_reap=0 ;;
    -h | --help) usage; return ;;
    *) die "sync: unknown option '$1'" ;;
  esac
  instances=$(running_instances)
  write_ssh_conf "$instances"
  if ((do_reap)); then reap "$instances"; fi
}

# Resolve an SSH alias (vast, vast-ID) to the instance ID by matching the
# hostname/port ssh would use against the running instances.
resolve_id() {
  local alias=$1 host port
  if [[ $alias =~ ^vast-([0-9]+)$ ]]; then
    echo "${BASH_REMATCH[1]}"
    return
  fi
  host=$(ssh -G "$alias" | awk '$1 == "hostname" {print $2}')
  port=$(ssh -G "$alias" | awk '$1 == "port" {print $2}')
  running_instances | jq -sr --arg h "$host" --argjson p "$port" \
    'map(select(.host == $h and .port == $p)) | first // empty | .id' |
    grep . || die "bootstrap: '$alias' ($host:$port) is not a running instance; run 'vastutils sync'"
}

cmd_bootstrap() {
  [[ ${1:-} == -h || ${1:-} == --help ]] && { usage; return; }
  (($# >= 2)) || die "usage: vastutils bootstrap <vast-ID|vast> <owner/repo>..."
  local alias=$1 id title known_hosts
  shift
  id=$(resolve_id "$alias")
  title="vast-$id"

  # Pin GitHub's host keys from the authenticated API rather than trusting
  # whatever the (untrusted) instance's network says on first connect.
  known_hosts=$(gh api meta --jq '.ssh_keys[] | "github.com " + .') ||
    die "bootstrap: 'gh api meta' failed; run 'gh auth login'"

  mkdir -p "$STATE_DIR"
  for repo in "$@"; do
    [[ $repo =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || die "bootstrap: '$repo' is not owner/repo"
    local k="gh_${repo//\//__}" pub
    echo "bootstrap: $title <- $repo"

    # $k/$title/$repo are validated above and expand locally on purpose.
    # shellcheck disable=SC2029
    pub=$(ssh "${SSH_OPTS[@]}" "$alias" "mkdir -p ~/.ssh && chmod 700 ~/.ssh &&
      { test -f ~/.ssh/$k || ssh-keygen -q -t ed25519 -N '' -C '$title $repo' -f ~/.ssh/$k; } &&
      cat ~/.ssh/$k.pub") || die "bootstrap: could not reach $alias"

    if gh repo deploy-key list --repo "$repo" --json key --jq '.[].key' |
      grep -qF "$(awk '{print $2}' <<<"$pub")"; then
      echo "  deploy key already registered"
    else
      local tmp
      tmp=$(mktemp)
      echo "$pub" >"$tmp"
      gh repo deploy-key add "$tmp" --repo "$repo" --title "$title" --allow-write
      rm -f "$tmp"
    fi
    printf '%s\t%s\n' "$repo" "$title" >>"$KEYS_DB"
    sort -u -o "$KEYS_DB" "$KEYS_DB"

    # shellcheck disable=SC2087 # expand locally on purpose
    ssh "${SSH_OPTS[@]}" "$alias" bash -s <<EOF
set -e
touch ~/.ssh/config ~/.ssh/known_hosts_github
chmod 600 ~/.ssh/config
cat > ~/.ssh/known_hosts_github <<'KH'
$known_hosts
KH
if ! grep -qx 'Host $k' ~/.ssh/config; then
  cat >> ~/.ssh/config <<'CFG'

Host $k
  HostName github.com
  User git
  IdentityFile ~/.ssh/$k
  IdentitiesOnly yes
  UserKnownHostsFile ~/.ssh/known_hosts_github
CFG
fi
command -v git >/dev/null || { echo "  git not installed on instance; skipping git config"; exit 0; }
git config --global --unset-all 'url.git@$k:$repo.git.insteadOf' || true
git config --global --add 'url.git@$k:$repo.git.insteadOf' 'https://github.com/$repo.git'
git config --global --add 'url.git@$k:$repo.git.insteadOf' 'git@github.com:$repo.git'
ssh -o BatchMode=yes -T $k 2>&1 | grep -q 'successfully authenticated' &&
  echo "  ok: instance can authenticate to GitHub" ||
  echo "  warning: GitHub auth test failed (key may take a few seconds to propagate)"
EOF
  done
}

cmd_status() {
  local instances
  instances=$(running_instances)
  echo "running instances:"
  jq -r '"  vast-\(.id)\t\(.host):\(.port)"' <<<"$instances"
  echo "recorded deploy keys:"
  if [[ -s $KEYS_DB ]]; then sed 's/^/  /' "$KEYS_DB"; else echo "  (none)"; fi
}

case "${1:-help}" in
  sync) shift; cmd_sync "$@" ;;
  bootstrap) shift; cmd_bootstrap "$@" ;;
  status) shift; cmd_status ;;
  help | -h | --help) usage ;;
  *) usage >&2; exit 2 ;;
esac
